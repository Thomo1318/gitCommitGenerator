"""Generate a markdown fixture index from committed suite/case JSON."""

from __future__ import annotations

import json
from pathlib import Path

from git_cg.eval.corpus.fixtures import default_fixture_root, load_fixture_dict


def _iter_case_files(root: Path) -> list[Path]:
    cases = root / "cases"
    if not cases.is_dir():
        return []
    return sorted(p for p in cases.rglob("*.json") if p.is_file())


def _iter_suite_files(root: Path) -> list[Path]:
    suites = root / "suites"
    if not suites.is_dir():
        return []
    return sorted(p for p in suites.glob("*.json") if p.is_file())


def build_fixture_index(*, fixture_root: Path | None = None) -> str:
    """Return markdown for the committed fixture corpus index."""
    root = fixture_root or default_fixture_root()
    try:
        from git_cg.eval.paths import REPO_ROOT

        root_display = root.resolve().relative_to(REPO_ROOT.resolve()).as_posix()
    except Exception:
        root_display = "tests/fixtures/eval"
    lines: list[str] = [
        "# Eval fixture index",
        "",
        "> Auto-generated by `python -m git_cg.eval.corpus.index`.",
        "> Do not hand-edit case tables; regenerate after fixture changes.",
        "",
        f"Fixture root: `{root_display}`",
        "",
        "## Suites",
        "",
        "| suite_id | case_count | notes |",
        "|:---|---:|:---|",
    ]
    for suite_path in _iter_suite_files(root):
        data = json.loads(suite_path.read_text(encoding="utf-8"))
        suite_id = data.get("suite_id") or suite_path.stem
        case_ids = data.get("case_ids") or []
        notes = (data.get("notes") or "").replace("|", "\\|").replace("\n", " ")
        lines.append(f"| `{suite_id}` | {len(case_ids)} | {notes} |")

    lines.extend(
        [
            "",
            "## Cases",
            "",
            "| case_id | path | regime | artifact_class | bound | seed_id | tags |",
            "|:---|:---|:---|:---|:---|:---|:---|",
        ]
    )
    for path in _iter_case_files(root):
        rel = path.relative_to(root).as_posix()
        try:
            data = load_fixture_dict(path)
        except Exception as exc:  # pragma: no cover - index should surface bad files
            lines.append(f"| _(unreadable)_ | `{rel}` |  |  |  |  | {exc} |")
            continue
        case_id = data.get("case_id") or path.stem
        regime = data.get("regime", "")
        artifact = data.get("artifact_class", "")
        bound = data.get("bound", "")
        meta = data.get("meta") if isinstance(data.get("meta"), dict) else {}
        seed_id = meta.get("seed_id", "")
        tags = ", ".join(data.get("tags") or [])
        lines.append(f"| `{case_id}` | `{rel}` | {regime} | `{artifact}` | {bound} | {seed_id} | {tags} |")

    lines.extend(
        [
            "",
            "## Golden artifacts",
            "",
            "| kind | path |",
            "|:---|:---|",
            "| core bundles | `bundles/cm-eval-fixtures-core/*.ape_bundle_v1.json` |",
            "| core snapshot | `snapshots/cm-eval-fixtures-core.dataset_snapshot_v1.json` |",
            "| archive bundles | `bundles/204-archive/*.ape_bundle_v1.json` |",
            "| archive snapshot | `snapshots/204-archive.dataset_snapshot_v1.json` |",
            "",
            "## Regeneration",
            "",
            "```bash",
            "uv run python -m git_cg.eval.corpus.index --write",
            "uv run python -m git_cg.eval.corpus.materialize",
            "```",
            "",
        ]
    )
    return "\n".join(lines) + "\n"


def write_fixture_index(
    *,
    fixture_root: Path | None = None,
    out_path: Path | None = None,
) -> Path:
    root = fixture_root or default_fixture_root()
    target = out_path or (root / "FIXTURE_INDEX.md")
    target.write_text(build_fixture_index(fixture_root=root), encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description="Generate eval fixture index markdown")
    parser.add_argument("--write", action="store_true", help="Write tests/fixtures/eval/FIXTURE_INDEX.md")
    parser.add_argument("--root", type=Path, default=None, help="Fixture root override")
    args = parser.parse_args(argv)
    if args.write:
        path = write_fixture_index(fixture_root=args.root)
        print(path)
    else:
        print(build_fixture_index(fixture_root=args.root), end="")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
